//! Raw C ABI over `vtty` (byte-cursor parser). Declared in `vtty_ffi.h`.
//!
//! ## Usage
//!
//! ```c
//! #include "vtty_ffi.h"
//!
//! vt_state *s = vt_new();
//! vt_advance(s, (const uint8_t *)"hello\nworld", 11);
//!
//! size_t rows = vt_line_count(s);     // 2
//! size_t len  = vt_text_len(s);       // 11
//! size_t start, end;
//! vt_line_range(s, 1, &start, &end);  // start=6, end=11
//!
//! vt_free(s);
//! ```
//!
//! API: `vt_version` · `vt_new` · `vt_free` · `vt_reset` · `vt_advance` ·
//! `vt_flush` · `vt_text` · `vt_text_len` · `vt_cursor` · `vt_line_count` ·
//! `vt_cursor_row` · `vt_cursor_col` · `vt_line_range`.
//!
//! Build: `cargo build -p vtty_ffi` (cdylib + staticlib).
//!
//! ## Example
//!
//! `examples/term_demo.c` spawns a shell on a pseudo-terminal and runs it as
//! a minimal interactive terminal (keystrokes in, shell output out). See the
//! file's header for build instructions.

#![expect(
    missing_debug_implementations,
    reason = "opaque FFI state does not need Debug"
)]

use std::ffi::c_char;

// Generated by build.rs from the package version (0x00MMNNPP).
include!(concat!(env!("OUT_DIR"), "/version.rs"));

/// Opaque parser + screen state. The fields are private so C code cannot
/// touch the Rust layout; it must use the accessor functions.
pub struct VtState {
    parser: vtty::Parser,
    state: vtty::State,
}

/// Borrow a non-null state pointer for the duration of the call.
///
/// # Safety
/// `state` must be null or a live [`vt_new`] pointer valid for the call.
#[inline]
unsafe fn state_ref(state: *const VtState) -> Option<&'static VtState> {
    if state.is_null() {
        None
    } else {
        // SAFETY: non-null, and the caller upholds the pointer contract.
        Some(unsafe { &*state })
    }
}

/// Borrow a non-null state pointer mutably for the duration of the call.
///
/// # Safety
/// `state` must be null or a live [`vt_new`] pointer valid for the call.
#[inline]
unsafe fn state_mut(state: *mut VtState) -> Option<&'static mut VtState> {
    if state.is_null() {
        None
    } else {
        // SAFETY: non-null, and the caller upholds the pointer contract.
        Some(unsafe { &mut *state })
    }
}

/// The ABI version as `(major << 16) | (minor << 8) | patch` — a compile-time
/// constant generated by `build.rs` from the workspace package `version`.
#[must_use]
#[unsafe(no_mangle)]
pub extern "C" fn vt_version() -> u32 {
    VERSION
}

/// Allocate a fresh parser + byte-cursor state.
///
/// # Safety
/// The returned pointer must be released with [`vt_free`].
#[must_use]
#[unsafe(no_mangle)]
pub extern "C" fn vt_new() -> *mut VtState {
    Box::into_raw(Box::new(VtState {
        // `simd` is enabled in Cargo.toml, so select the SIMD fast path.
        parser: vtty::Parser::with_simd(),
        state: vtty::State::new(),
    }))
}

/// Release a state allocated by [`vt_new`].
///
/// # Safety
/// `state` must be null or a pointer from [`vt_new`], and must not be used
/// after the call.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_free(state: *mut VtState) {
    if !state.is_null() {
        // SAFETY: `state` came from `vt_new` and is no longer used by the caller.
        unsafe { drop(Box::from_raw(state)) };
    }
}

/// Reset the parser and screen state to empty (text, cursor, and any partial
/// parse state are cleared). The pointer stays valid for reuse.
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer (or null, which is a no-op).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_reset(state: *mut VtState) {
    if let Some(s) = unsafe { state_mut(state) } {
        s.parser.reset();
        s.state = vtty::State::new();
    }
}

/// Feed a byte slice to the parser.
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer and `bytes` must point to `len`
/// valid bytes for the duration of the call.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_advance(state: *mut VtState, bytes: *const u8, len: usize) {
    // A null state or an empty/null input is a no-op.
    if bytes.is_null() || len == 0 {
        return;
    }
    if let Some(s) = unsafe { state_mut(state) } {
        // SAFETY: `bytes` is valid for `len` bytes (caller contract).
        let bytes = unsafe { std::slice::from_raw_parts(bytes, len) };
        s.parser.advance(&mut s.state, bytes);
    }
}

/// Close the stream: emit a pending partial UTF-8 code point as U+FFFD.
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer (or null, which is a no-op).
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_flush(state: *mut VtState) {
    if let Some(s) = unsafe { state_mut(state) } {
        s.parser.flush(&mut s.state);
    }
}

/// The accumulated text buffer (valid UTF-8, NOT NUL-terminated).
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer. The returned pointer is valid
/// until the next mutation of `state` and must be combined with
/// [`vt_text_len`].
#[must_use]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_text(state: *const VtState) -> *const c_char {
    match unsafe { state_ref(state) } {
        Some(s) => s.state.text.as_ptr().cast(),
        None => std::ptr::null(),
    }
}

/// Byte length of [`vt_text`].
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer.
#[must_use]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_text_len(state: *const VtState) -> usize {
    match unsafe { state_ref(state) } {
        Some(s) => s.state.text.len(),
        None => 0,
    }
}

/// Current cursor as a BYTE offset into [`vt_text`].
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer.
#[must_use]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_cursor(state: *const VtState) -> usize {
    match unsafe { state_ref(state) } {
        Some(s) => s.state.cursor,
        None => 0,
    }
}

/// Number of lines in the buffer. An empty buffer has 0 lines; each `\n`
/// starts a new line (a trailing `\n` counts as one empty line).
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer.
#[must_use]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_line_count(state: *const VtState) -> usize {
    match unsafe { state_ref(state) } {
        Some(s) => s.state.line_count(),
        None => 0,
    }
}

/// 0-based row (line index) of the cursor.
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer.
#[must_use]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_cursor_row(state: *const VtState) -> usize {
    match unsafe { state_ref(state) } {
        Some(s) => s.state.cursor_row(),
        None => 0,
    }
}

/// 0-based BYTE column of the cursor within its line (offset from the line
/// start, not the terminal cell column — this byte-cursor state has no cell
/// grid).
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer.
#[must_use]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_cursor_col(state: *const VtState) -> usize {
    match unsafe { state_ref(state) } {
        Some(s) => s.state.cursor_col(),
        None => 0,
    }
}

/// Fill `*start`/`*end` with the byte range of line `line` (0-based) into
/// [`vt_text`]; `*end` is exclusive (points at the line's `\n`). Returns
/// `false` (leaving the pointers untouched) when `line` is out of range.
///
/// # Safety
/// `state` must be a live [`vt_new`] pointer; `start`/`end` valid `usize`
/// pointers.
#[must_use]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn vt_line_range(
    state: *const VtState,
    line: usize,
    start: *mut usize,
    end: *mut usize,
) -> bool {
    if start.is_null() || end.is_null() {
        return false;
    }
    let Some(s) = (unsafe { state_ref(state) }) else {
        return false;
    };
    let Some(range) = s.state.line_range(line) else {
        return false;
    };

    // SAFETY: `start`/`end` are valid writable pointers (checked non-null).
    unsafe {
        *start = range.start;
        *end = range.end;
    }
    true
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Drive a state through printable text, a newline, a reset, and the
    /// cursor/line accessors, verifying every accessor round-trips.
    #[test]
    fn accessors_round_trip() {
        // SAFETY: `vt_new` returns a valid, owned state; inputs are valid.
        unsafe {
            let s = vt_new();
            assert!(!s.is_null());

            vt_advance(s, b"hello".as_ptr(), 5);
            assert_eq!(vt_text_len(s), 5);
            assert_eq!(vt_cursor(s), 5);
            assert_eq!(vt_line_count(s), 1);
            assert_eq!(vt_cursor_row(s), 0);
            assert_eq!(vt_cursor_col(s), 5);

            vt_advance(s, b"\nworld".as_ptr(), 6);
            assert_eq!(vt_text_len(s), 11);
            assert_eq!(vt_line_count(s), 2);
            assert_eq!(vt_cursor_row(s), 1);
            assert_eq!(vt_cursor_col(s), 5);

            let mut start = usize::MAX;
            let mut end = usize::MAX;
            assert!(vt_line_range(s, 0, &mut start, &mut end));
            assert_eq!((start, end), (0, 5));
            assert!(vt_line_range(s, 1, &mut start, &mut end));
            assert_eq!((start, end), (6, 11));
            // Out of range: returns false and leaves start/end untouched.
            let before = (start, end);
            assert!(!vt_line_range(s, 2, &mut start, &mut end));
            assert_eq!((start, end), before);

            vt_reset(s);
            assert_eq!(vt_text_len(s), 0);
            assert_eq!(vt_cursor(s), 0);
            assert_eq!(vt_line_count(s), 0);

            vt_free(s);
        }
    }

    /// Null pointers are a no-op / safe default, never UB.
    #[test]
    fn null_state_is_safe() {
        unsafe {
            assert_eq!(vt_text(std::ptr::null()), std::ptr::null());
            assert_eq!(vt_text_len(std::ptr::null()), 0);
            assert_eq!(vt_cursor(std::ptr::null()), 0);
            assert_eq!(vt_line_count(std::ptr::null()), 0);
            assert_eq!(vt_cursor_row(std::ptr::null()), 0);
            assert_eq!(vt_cursor_col(std::ptr::null()), 0);
            assert!(!vt_line_range(
                std::ptr::null(),
                0,
                std::ptr::null_mut(),
                std::ptr::null_mut(),
            ));
            vt_advance(std::ptr::null_mut(), std::ptr::null(), 0);
            vt_reset(std::ptr::null_mut());
            vt_free(std::ptr::null_mut());
        }
    }

    /// `\r` is normalized to `\n`, so a CRLF pair becomes two line breaks in
    /// this byte-cursor state.
    #[test]
    fn cr_is_a_line_break() {
        unsafe {
            let s = vt_new();
            vt_advance(s, b"a\r\nb".as_ptr(), 4);
            assert_eq!(vt_text_len(s), 4);
            assert_eq!(vt_line_count(s), 3); // "a", "", "b"
            assert_eq!(vt_cursor_row(s), 2);
            assert_eq!(vt_cursor_col(s), 1);
            vt_free(s);
        }
    }
}
